namespace NativeCollections
{
    /// <summary>
    ///     Represents resource identifiers for localized exception message templates.
    /// </summary>
    internal enum ExceptionResource
    {
        /// <summary>
        ///     The resource key for an error indicating that an ASCII digit was expected.
        /// </summary>
        Format_ExpectedAsciiDigit,

        /// <summary>
        ///     The resource key for an error indicating that a format item was not closed.
        /// </summary>
        Format_UnclosedFormatItem,

        /// <summary>
        ///     The resource key for an error indicating that a closing brace was unexpected.
        /// </summary>
        Format_UnexpectedClosingBrace
    }
}